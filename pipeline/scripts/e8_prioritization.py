"""
e8_prioritization.py -- final SNP-Lib + NP-library prioritization (E8).

Produces two outputs, kept explicitly separate because they carry different
evidentiary weight and different roles in the paper's narrative:

1. NP-library shortlist (the top 500 compounds that went through full-
   protocol redocking): a ranked, confidence-tiered list combining SBDD
   (full-protocol Vina score + on-pocket pose check, ADR-AIIM-085) and LBDD
   (Mondrian conformal prediction, ADR-AIIM-081) evidence. This is the
   paper's actual output -- a set of computational hypotheses.

2. Original SNP-Lib (236 compounds): a diagnostic summary combining
   multi-space applicability-domain status (E2, ADR-AIIM-073) and LBDD
   status. This library was never re-docked in the rescue effort -- the
   docking rescue techniques (Asn253/IFP/ensemble, ADR-AIIM-075/076/078)
   were tested against it and found null, and its 0/236 LBDD result
   (ADR-AIIM-077) is what motivated the library expansion in the first
   place. It is reported here as diagnosed context, not as a second ranked
   hit list -- SNP-Lib produced no actionable computational leads in this
   session's rescue.

Tier logic for the NP-library shortlist (grounded in the actual evidence
distribution observed, not an arbitrary a priori cutoff -- see inline
comments):
  Tier A "converging evidence"   : on-pocket pose AND LBDD does not
                                    confidently exclude activity
                                    (prediction_set_sig0.05 == "{0,1}")
  Tier B "strong SBDD, LBDD null": on-pocket pose AND vina_score in the
                                    strongest quartile of the 497
                                    successfully-docked compounds, but LBDD
                                    confidently inactive
  Tier C "supporting SBDD only"  : on-pocket pose, remaining compounds
  Flagged "off-pocket"           : docked successfully but the pose's
                                    centroid falls outside the on-pocket
                                    distance cutoff -- listed, not tiered,
                                    since pose geometry itself is in doubt
  Flagged "docking failed"       : the 3 manually-skipped pathological
                                    compounds (ADR-AIIM-084), reported for
                                    completeness, not ranked

Every row in both outputs is explicitly labelled a computational
hypothesis. No wet-lab data exists or is used anywhere in this pipeline.

Usage:
    python e8_prioritization.py --out <dir>
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from kdss_paths import project_root, resolve, under

import pandas as pd

ROOT = project_root()
FUNNEL_RUN = resolve("20_new_runs/np_library_funnel_2026-08-15")
QSAR_RUN = resolve("20_new_runs/qsar_lbdd_2026-08-07")
AD_RUN = resolve("20_new_runs/ad_descriptor_sweep_2026-08-15")
SNP_LIB_CSV = resolve("02_frozen_inputs/snp_library/01_library_validated.csv")

DISCLAIMER = (
    "Every compound listed is a computational hypothesis only, generated by "
    "an in silico pipeline (docking + a frozen QSAR model wrapped in "
    "conformal prediction). No wet-lab binding, activity, or toxicity data "
    "exists for any compound in this table. Ranking and tiering reflect "
    "convergence and strength of computational evidence, not validated "
    "bioactivity."
)


def build_np_library_shortlist(outdir: Path) -> pd.DataFrame:
    dock = pd.concat(
        [pd.read_csv(FUNNEL_RUN / f"full_scores_chunk{c}.csv") for c in (1, 2, 3)],
        ignore_index=True,
    )
    ledger = pd.concat(
        [pd.read_csv(FUNNEL_RUN / f"full_ledger_chunk{c}.csv") for c in (1, 2, 3)],
        ignore_index=True,
    )
    conf = pd.read_csv(under("20_new_runs/np_library_funnel_2026-08-15", "nplibrary_conformal_predictions.csv"))

    m = dock.merge(
        ledger[["compound_id", "organism_name", "is_orchidaceae",
                "structure_taxonomy_npclassifier_02superclass",
                "structure_taxonomy_npclassifier_03class",
                "pharmacophore_2d_score", "shape_pharm_3d_score",
                "funnel_rank", "fastpass_vina_score", "SMILES"]],
        on="compound_id", how="left",
    ).merge(
        conf[["compound_id", "p_active_calibrated", "conformal_p_active",
              "conformal_p_inactive", "prediction_set_sig0.05"]],
        on="compound_id", how="left",
    )

    failed = m[m.status == "failed"].copy()
    ok = m[m.status == "ok"].copy()
    off_pocket = ok[ok.on_pocket == False].copy()  # noqa: E712
    on_pocket = ok[ok.on_pocket == True].copy()  # noqa: E712

    vina_q25 = on_pocket.vina_score.quantile(0.25)

    is_borderline = on_pocket["prediction_set_sig0.05"] == "{0,1}"
    is_strong_sbdd = on_pocket.vina_score <= vina_q25

    on_pocket["tier"] = "C_supporting_sbdd_only"
    on_pocket.loc[is_strong_sbdd & ~is_borderline, "tier"] = "B_strong_sbdd_lbdd_null"
    on_pocket.loc[is_borderline, "tier"] = "A_converging_sbdd_lbdd"

    off_pocket["tier"] = "flagged_off_pocket_pose"
    failed["tier"] = "flagged_docking_failed"

    final = pd.concat([on_pocket, off_pocket, failed], ignore_index=True)
    tier_order = {
        "A_converging_sbdd_lbdd": 0, "B_strong_sbdd_lbdd_null": 1,
        "C_supporting_sbdd_only": 2, "flagged_off_pocket_pose": 3,
        "flagged_docking_failed": 4,
    }
    final["_tier_sort"] = final.tier.map(tier_order)
    final = final.sort_values(
        ["_tier_sort", "vina_score"], na_position="last"
    ).drop(columns="_tier_sort").reset_index(drop=True)
    final.insert(0, "rank", range(1, len(final) + 1))

    cols = [
        "rank", "compound_id", "tier", "status", "failure_reason",
        "vina_score", "vina_mean_top3", "on_pocket", "centroid_dist_A",
        "p_active_calibrated", "prediction_set_sig0.05",
        "mol_formula", "n_heavy_atoms", "n_rotatable_bonds",
        "structure_taxonomy_npclassifier_02superclass",
        "structure_taxonomy_npclassifier_03class", "organism_name",
        "is_orchidaceae", "pharmacophore_2d_score", "shape_pharm_3d_score",
        "fastpass_vina_score", "funnel_rank", "SMILES",
    ]
    final = final[cols]
    final.to_csv(outdir / "e8_np_library_prioritization.csv", index=False)

    tier_counts = final.tier.value_counts().to_dict()
    return final, tier_counts, vina_q25


def build_snplib_diagnostic(outdir: Path) -> pd.DataFrame:
    lib = pd.read_csv(SNP_LIB_CSV)[
        ["Compound", "Compound name", "Groups", "MW", "SMILES_std", "Plants"]
    ].rename(columns={
        "Compound": "compound_id", "Compound name": "compound_name",
        "Groups": "npclassifier_group", "MW": "mw",
        "SMILES_std": "smiles", "Plants": "organism_name",
    })
    ad = pd.read_csv(under("20_new_runs/ad_descriptor_sweep_2026-08-15", "ad_per_compound.csv")).rename(
        columns={"compound_id": "compound_id"}
    )
    conf = pd.read_csv(under("20_new_runs/qsar_lbdd_2026-08-07", "snplib_conformal_predictions.csv")).rename(
        columns={"SNP_ID": "compound_id"}
    )

    m = lib.merge(ad, on="compound_id", how="left").merge(
        conf[["compound_id", "p_active_calibrated",
              "prediction_set_sig0.05"]],
        on="compound_id", how="left",
    )
    m["any_space_in_domain"] = m.n_spaces_inside.fillna(0) > 0
    m["lbdd_borderline_or_active"] = m["prediction_set_sig0.05"] != "{0}"

    cols = [
        "compound_id", "compound_name", "npclassifier_group", "mw",
        "organism_name", "n_spaces_inside", "any_space_in_domain",
        "PhysChem_sim", "p_active_calibrated", "prediction_set_sig0.05",
        "lbdd_borderline_or_active", "smiles",
    ]
    m = m[cols].sort_values("compound_id").reset_index(drop=True)
    m.to_csv(outdir / "e8_snplib_diagnostic_summary.csv", index=False)
    return m


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(FUNNEL_RUN))
    args = ap.parse_args()
    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    np_final, tier_counts, vina_q25 = build_np_library_shortlist(outdir)
    snp_final = build_snplib_diagnostic(outdir)

    tier_a = np_final[np_final.tier == "A_converging_sbdd_lbdd"]
    headline = tier_a[["compound_id", "vina_score", "p_active_calibrated",
                        "structure_taxonomy_npclassifier_03class",
                        "organism_name"]].to_dict(orient="records")

    snp_any_domain = int(snp_final.any_space_in_domain.sum())
    snp_lbdd_flagged = int(snp_final.lbdd_borderline_or_active.sum())

    summary = {
        "disclaimer": DISCLAIMER,
        "np_library_shortlist": {
            "n_total": len(np_final),
            "n_source": "top 500 by fast-pass Vina score, from a 5,000-"
                        "compound biosynthetic-class-anchored NP-library "
                        "pool (LOTUS-derived), full-protocol redocked "
                        "(8 conformers, exhaustiveness 32, 10 poses)",
            "tier_counts": tier_counts,
            "tier_definitions": {
                "A_converging_sbdd_lbdd": "on-pocket pose AND LBDD "
                    "conformal prediction does not confidently exclude "
                    "activity (sig=0.05 prediction set = {0,1})",
                "B_strong_sbdd_lbdd_null": "on-pocket pose, vina_score in "
                    f"strongest quartile (<= {vina_q25:.3f} kcal/mol) of "
                    "the 497 successfully-docked compounds, LBDD "
                    "confidently inactive",
                "C_supporting_sbdd_only": "on-pocket pose, remaining "
                    "compounds",
                "flagged_off_pocket_pose": "docked successfully but pose "
                    "centroid outside the on-pocket cutoff -- pose "
                    "geometry itself in doubt",
                "flagged_docking_failed": "manually skipped after "
                    "repeated timeout on a pathological glycoside "
                    "(ADR-AIIM-084); not ranked",
            },
            "vina_score_top_quartile_threshold_kcal_mol": round(float(vina_q25), 3),
            "headline_tier_a_compounds": headline,
        },
        "snplib_original_236_diagnostic": {
            "n_total": len(snp_final),
            "n_in_domain_any_of_6_structural_spaces": snp_any_domain,
            "n_lbdd_not_confidently_inactive": snp_lbdd_flagged,
            "role_in_paper": "diagnostic context only, not a ranked hit "
                "list -- this library produced no computational leads in "
                "this session's rescue; its near-total AD/LBDD exclusion "
                "(quantified in E2/ADR-AIIM-073 and ADR-AIIM-077) is what "
                "motivated the LOTUS-derived library expansion "
                "(ADR-AIIM-079) that produced the NP-library shortlist "
                "above",
        },
    }
    (outdir / "e8_summary.json").write_text(json.dumps(summary, indent=2, default=str))

    print(f"NP-library shortlist: {len(np_final)} compounds")
    print(f"  tier counts: {tier_counts}")
    print(f"  vina top-quartile threshold: {vina_q25:.3f} kcal/mol")
    print(f"\nTier A (converging SBDD+LBDD evidence), n={len(tier_a)}:")
    for r in headline:
        print(f"  {r['compound_id']}: vina={r['vina_score']:.3f}, "
              f"p_active={r['p_active_calibrated']:.3f}, "
              f"{r['structure_taxonomy_npclassifier_03class']}, "
              f"{r['organism_name']}")
    print(f"\nSNP-Lib (236) diagnostic: {snp_any_domain}/{len(snp_final)} in "
          f"AD in any of 6 structural spaces; "
          f"{snp_lbdd_flagged}/{len(snp_final)} not confidently LBDD-inactive")
    print(f"\nwritten -> {outdir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
